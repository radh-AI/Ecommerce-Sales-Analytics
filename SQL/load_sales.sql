    NULLIF(TRIM(s.customer_country), ''),
    NULLIF(TRIM(s.region), ''),
    NULLIF(TRIM(s.customer_postal_code), ''),
    NULLIF(TRIM(s.payment_method), ''),
    NULLIF(TRIM(s.payment_status), ''),
